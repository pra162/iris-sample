from typing import Iterable

import psycopg
from psycopg.types.json import Jsonb

from app.scrapers.uvp.models import UvpRecord

CREATE_STAGING_SCHEMA = "CREATE SCHEMA IF NOT EXISTS iris_staging"
CREATE_STAGING_TABLE = """
CREATE TABLE IF NOT EXISTS iris_staging.signal_ingest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL,
    source_id TEXT NOT NULL,
    signal_type TEXT NOT NULL,
    title TEXT NOT NULL,
    publication_date DATE,
    source_updated_at DATE,
    source_result_date DATE,
    source_url TEXT NOT NULL,
    location_text TEXT,
    source_bbox JSONB,
    geometry geometry(Point, 25832),
    quality_flags TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    raw_payload JSONB NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_signal_ingest_source_record_type
        UNIQUE (source_name, source_id, signal_type)
);
"""
ADD_SOURCE_RESULT_DATE = """
ALTER TABLE iris_staging.signal_ingest
ADD COLUMN IF NOT EXISTS source_result_date DATE
"""

UPSERT_SIGNAL = """
INSERT INTO iris_staging.signal_ingest (
    source_name, source_id, signal_type, title, publication_date,
    source_updated_at, source_result_date, source_url, location_text, source_bbox, geometry,
    quality_flags, raw_payload
) VALUES (
    'uvp_verbund', %s, %s, %s, %s, %s, %s, %s, %s, %s,
    CASE
        WHEN %s::double precision IS NULL OR %s::double precision IS NULL THEN NULL
        ELSE ST_SetSRID(ST_MakePoint(%s, %s), 25832)
    END,
    %s, %s
)
ON CONFLICT (source_name, source_id, signal_type) DO UPDATE SET
    title = EXCLUDED.title,
    publication_date = EXCLUDED.publication_date,
    source_updated_at = EXCLUDED.source_updated_at,
    source_result_date = EXCLUDED.source_result_date,
    source_url = EXCLUDED.source_url,
    location_text = EXCLUDED.location_text,
    source_bbox = EXCLUDED.source_bbox,
    geometry = EXCLUDED.geometry,
    quality_flags = EXCLUDED.quality_flags,
    raw_payload = EXCLUDED.raw_payload,
    ingested_at = now()
"""


def ensure_staging_table(connection: psycopg.Connection) -> None:
    with connection.cursor() as cursor:
        cursor.execute("CREATE EXTENSION IF NOT EXISTS postgis")
        cursor.execute(CREATE_STAGING_SCHEMA)
        cursor.execute(CREATE_STAGING_TABLE)
        cursor.execute(ADD_SOURCE_RESULT_DATE)


def upsert_records(
    connection: psycopg.Connection,
    records: Iterable[UvpRecord],
) -> int:
    count = 0
    with connection.cursor() as cursor:
        for record in records:
            cursor.execute(
                UPSERT_SIGNAL,
                (
                    record.source_id,
                    record.signal_type,
                    record.title,
                    record.publication_date,
                    record.source_updated_at,
                    record.source_result_date,
                    record.source_url,
                    record.location_text,
                    Jsonb(record.source_bbox) if record.source_bbox is not None else None,
                    record.geometry_x,
                    record.geometry_y,
                    record.geometry_x,
                    record.geometry_y,
                    record.quality_flags,
                    Jsonb(record.raw_payload),
                ),
            )
            count += 1
    return count


def normalize_database_url(database_url: str) -> str:
    return (
        database_url.replace("postgresql+psycopg://", "postgresql://", 1)
        .replace("postgresql+psycopg2://", "postgresql://", 1)
    )
